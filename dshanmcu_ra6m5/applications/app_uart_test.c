void app_uart_test(void)
{
    fsp_err_t err;
    uint8_t a,b;

    err = drv_uart_init();
    if(FSP_SUCCESS != err) __BKPT();
    printf("test\r\n");
    while (1)
    {
        a = 0;
        b = 0;
        printf("enter two number:\r\n");
        fflush(stdout);
        int n = scanf("%lu %lu", &a, &b);
        if (2 != n)
        {
            printf("scanf failed, n=%d\r\n", n);
            continue;
        }
        printf("a + b = %lu\r\n", (unsigned long)(a + b));
    }
}



